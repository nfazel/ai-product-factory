import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

/**
 * A preload module for the acceptance test processes. The framework writes it outside the verification worktree and
 * the Verification Agent cannot change it. It is loaded with NODE_OPTIONS=--import, so it runs before any test file.
 *
 * It does two things:
 * - It refuses every TCP connection except to 127.0.0.1 or localhost on the managed application's port, and it
 *   refuses fetch() to any other origin. This is a chokepoint, not a sandbox: a test that deliberately spawns its own
 *   process is outside what this guard can stop, and the adapter documents that limit.
 * - It records each request's method, path, status and duration to an observations file. Bodies, headers and query
 *   strings are not recorded, so credentials cannot reach the evidence through this file.
 */
export const GUARD_SOURCE = `// Written by the AI Product Builder verification framework. Not generated by the Verification Agent.
import net from "node:net";
import fs from "node:fs";

const base = new URL(process.env.VERIFICATION_BASE_URL);
const allowedPort = Number(base.port);
const allowedHosts = new Set(["127.0.0.1", "localhost"]);
const observationsFile = process.env.VERIFICATION_OBSERVATIONS_FILE || "";

function refuse(target) {
  const error = new Error(
    "Verification guard refused " + target + ". Verification tests may reach only the managed application at " + base.origin + ".",
  );
  error.code = "VERIFICATION_GUARD";
  return error;
}

const originalConnect = net.Socket.prototype.connect;
net.Socket.prototype.connect = function guardedConnect(...args) {
  // Node passes [options, callback] as one array on some paths, such as fetch's connections. Unwrap it. Anything the
  // guard still cannot read gets NaN for its port and is refused, so an unknown destination fails closed.
  const first = Array.isArray(args[0]) ? args[0][0] : args[0];
  let host = "localhost";
  let port = NaN;
  let pipe = null;
  if (first && typeof first === "object") {
    port = Number(first.port);
    host = first.host || "localhost";
    if (first.path) pipe = String(first.path);
  } else {
    port = Number(first);
    if (typeof args[1] === "string") host = args[1];
  }
  if (pipe !== null || !allowedHosts.has(host) || port !== allowedPort) {
    const error = refuse(pipe !== null ? "a local socket" : host + ":" + port);
    process.nextTick(() => this.destroy(error));
    return this;
  }
  return originalConnect.apply(this, args);
};

const originalFetch = globalThis.fetch;
function record(entry) {
  if (!observationsFile) return;
  fs.appendFileSync(observationsFile, JSON.stringify(entry) + "\\n");
}

globalThis.fetch = async function guardedFetch(input, init) {
  const isRequest = typeof Request !== "undefined" && input instanceof Request;
  const raw = isRequest ? input.url : input instanceof URL ? input.href : String(input);
  const target = new URL(raw, base);
  if (target.origin !== base.origin) throw refuse(target.origin);
  const method = String((init && init.method) || (isRequest ? input.method : "GET")).toUpperCase();
  const started = Date.now();
  let response;
  try {
    response = await originalFetch(isRequest ? new Request(target, input) : target, init);
  } catch (error) {
    record({ method, path: target.pathname, status: 0, ms: Date.now() - started, at: new Date().toISOString() });
    throw error;
  }
  record({ method, path: target.pathname, status: response.status, ms: Date.now() - started, at: new Date().toISOString() });
  return response;
};
`;

export const MAX_OBSERVATIONS = 500;

export type HttpObservation = {
  method: string;
  path: string;
  status: number;
  ms: number;
  at: string;
};

/** Writes the guard into the attempt's runtime directory and returns its file URL for NODE_OPTIONS. */
export function writeGuard(runtimeDir: string) {
  const file = path.join(runtimeDir, "verification-guard.mjs");
  fs.writeFileSync(file, GUARD_SOURCE, { mode: 0o600 });
  return { file, url: pathToFileURL(file).href };
}

/** Reads the observations a test process wrote. Unreadable or malformed lines are skipped, never trusted. */
export function readObservations(file: string): HttpObservation[] {
  if (!fs.existsSync(file)) return [];
  const observations: HttpObservation[] = [];
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line.trim()) continue;
    try {
      const parsed = JSON.parse(line) as Partial<HttpObservation>;
      if (typeof parsed.method !== "string" || typeof parsed.path !== "string" || typeof parsed.status !== "number") continue;
      observations.push({
        method: parsed.method.slice(0, 10),
        path: parsed.path.slice(0, 200),
        status: parsed.status,
        ms: typeof parsed.ms === "number" ? parsed.ms : 0,
        at: typeof parsed.at === "string" ? parsed.at.slice(0, 40) : "",
      });
    } catch {
      continue;
    }
    if (observations.length >= MAX_OBSERVATIONS) break;
  }
  return observations;
}
